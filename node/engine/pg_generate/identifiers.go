package pggenerate

// ident writes an identifier. A name that Postgres reserves is written in
// double quotes, so that Postgres reads it as a name and not as a keyword or
// as a built-in value: unquoted, a column named current_user would be read as
// the current role, and a column named default as the column's default.
// Kwil identifiers are lower case, which is what Postgres folds unquoted
// names to, so quoting never changes which object a name refers to. The
// legacy generator writes every identifier as is.
func (s *sqlGenerator) ident(name string) string {
	if s.legacy || !pgReservedWords[name] {
		return name
	}
	return `"` + name + `"`
}

